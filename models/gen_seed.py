"""Generates the Supabase seed migration from catalog.json and plans.json.

    python models/gen_seed.py

The migration only inserts missing rows (ON CONFLICT DO NOTHING), so changes
made in the admin dashboard are never overwritten by a redeploy.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "supabase" / "migrations" / "20261122000100_aro_catalog_seed.sql"


def q(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def render() -> str:
    catalog = json.loads((HERE / "catalog.json").read_text(encoding="utf-8"))
    plans = json.loads((HERE / "plans.json").read_text(encoding="utf-8"))
    currency = plans["currency"]
    lines = [
        "-- GENERATED by models/gen_seed.py from models/catalog.json and models/plans.json — do not edit by hand.",
        "-- Inserts missing rows only, so admin-dashboard changes survive redeploys.",
        "",
    ]
    for sort, m in enumerate(catalog["models"]):
        arch = m["architecture"]
        lines.append(
            "insert into public.aro_models (id, name, tagline, status, chat_selectable, served_name, endpoint, system_prompt, credit_cost, sort) values ("
            + ", ".join(q(v) for v in [m["id"], m["name"], m["tagline"], m["default_status"], m["chat_selectable"],
                                        arch.get("served_name"), arch["endpoint"], m.get("system_prompt", ""),
                                        plans["credit_costs"][m["id"]], sort])
            + ") on conflict (id) do nothing;"
        )
    lines.append("")
    for sort, p in enumerate(plans["plans"]):
        lines.append(
            "insert into public.aro_plans (id, name, price_minor, currency, priority, sort) values ("
            + ", ".join(q(v) for v in [p["id"], p["name"], p["price_minor"], currency, p["priority"], sort])
            + ") on conflict (id) do nothing;"
        )
        for model_id, limit in p["models"].items():
            lines.append(
                f"insert into public.aro_plan_models (plan_id, model_id, daily_limit) values ({q(p['id'])}, {q(model_id)}, {q(limit)}) "
                "on conflict do nothing;"
            )
    lines.append("")
    for c in plans["credit_packs"]:
        lines.append(
            "insert into public.aro_credit_packs (id, name, credits, price_minor, currency) values ("
            + ", ".join(q(v) for v in [c["id"], c["name"], c["credits"], c["price_minor"], currency])
            + ") on conflict (id) do nothing;"
        )
    for x in plans["model_products"]:
        lines.append(
            "insert into public.aro_model_products (id, model_id, name, price_minor, currency, duration_days, daily_limit) values ("
            + ", ".join(q(v) for v in [x["id"], x["model_id"], x["name"], x["price_minor"], currency, x["duration_days"], x["daily_limit"]])
            + ") on conflict (id) do nothing;"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUT}")
