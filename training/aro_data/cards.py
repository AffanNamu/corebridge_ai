"""Generates training/aro_data/DATASETS.md from the registry."""

from __future__ import annotations

import json
from pathlib import Path

from .registry import CATALOG_PATH, REGISTRY_PATH, load_registry

OUT = Path(__file__).resolve().parent / "DATASETS.md"

_BADGE = {
    "allowed": "✅ allowed",
    "conditional": "🟡 conditional",
    "eval_only": "🧪 eval only",
    "rag_only": "🔎 RAG only",
    "restricted": "⛔ restricted",
    "excluded": "❌ excluded",
    "unverified": "❓ unverified",
}


def render() -> str:
    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    datasets = load_registry()
    lines = [
        "# ARO datasets",
        "",
        f"Generated from `{REGISTRY_PATH.relative_to(REGISTRY_PATH.parents[2])}` — edit the registry, then run "
        "`python -m aro_data card`.",
        "",
        "| Status | Meaning |",
        "|---|---|",
        "| ✅ allowed | Cleared for commercial training (license checked; attribution may be required). |",
        "| 🟡 conditional | Usable only after a specific review (gated terms, per-file licenses, share-alike). |",
        "| 🧪 eval only | Benchmarks. Never enter training data. |",
        "| 🔎 RAG only | Looked up and cited at answer time, not trained on. |",
        "| ⛔ restricted | Rights problems (e.g. generated by models whose terms forbid training competitors). |",
        "| ❌ excluded | Non-commercial or withdrawn. |",
        "| ❓ unverified | License couldn't be read — don't use until checked. |",
        "",
        "Licenses were read from each dataset's Hugging Face card or official site on the date shown. "
        "A license tag is not the whole story: **have a lawyer review before a public commercial launch.**",
        "",
    ]
    for model in catalog["models"]:
        rows = [d for d in datasets if model["id"] in d.models]
        lines += [f"## {model['name']}", ""]
        if not rows:
            lines += ["_No datasets assigned yet._", ""]
            continue
        lines += ["| Dataset | Status | Use | License | Languages | Notes |", "|---|---|---|---|---|---|"]
        for d in sorted(rows, key=lambda d: (list(_BADGE).index(d.commercial_status), d.name)):
            langs = ", ".join(d.languages[:8]) + ("…" if len(d.languages) > 8 else "")
            lines.append(
                f"| [{d.name}]({d.source_url if d.source_url.startswith('http') else '../../' + d.source_url}) "
                f"| {_BADGE[d.commercial_status]} | {', '.join(d.usage) or '—'} | {d.license} | {langs} | {d.notes} |"
            )
        lines.append("")
    return "\n".join(lines)


def write(path: Path = OUT) -> Path:
    path.write_text(render(), encoding="utf-8")
    return path
