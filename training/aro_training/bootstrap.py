"""Starter data for ARO 1.5, used before (and alongside) user feedback.

  * OpenAssistant oasst2 — human-written, human-ranked conversations,
    Apache-2.0 (commercial use allowed). We keep the best-ranked reply at
    each turn.
  * seed/identity.jsonl — written by the ARO team so the model knows it is
    ARO 1.5 from ARO AI (not the base model's name).

We deliberately avoid datasets generated by ChatGPT/Claude/Gemini: their
terms forbid using outputs to train competing models.
"""

from __future__ import annotations

import json
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from .config import CONFIG

SEED_DIR = Path(__file__).resolve().parent.parent / "seed"


def build_oasst_threads(
    rows: Iterable[dict[str, Any]],
    system_prompt: str = CONFIG.system_prompt,
    langs: set[str] | None = None,
    max_turns: int = 4,
) -> list[dict[str, Any]]:
    """Turns oasst2 message rows into chat examples.

    For every root prompt, follows the best-ranked assistant reply (rank 0)
    and then the first user follow-up, up to `max_turns` exchanges. Each
    prefix that ends with an assistant reply becomes one example.
    """
    by_id: dict[str, dict[str, Any]] = {}
    children: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        # Skip deleted, rejected and machine-written (synthetic) messages.
        if row.get("deleted") or row.get("review_result") is False or row.get("synthetic"):
            continue
        by_id[row["message_id"]] = row
        if row.get("parent_id"):
            children[row["parent_id"]].append(row)

    def best_reply(parent_id: str) -> dict[str, Any] | None:
        replies = [c for c in children.get(parent_id, []) if c["role"] == "assistant" and c.get("rank") is not None]
        return min(replies, key=lambda c: c["rank"]) if replies else None

    def first_followup(parent_id: str) -> dict[str, Any] | None:
        prompts = [c for c in children.get(parent_id, []) if c["role"] == "prompter"]
        return prompts[0] if prompts else None

    examples: list[dict[str, Any]] = []
    for row in by_id.values():
        if row.get("parent_id") or row["role"] != "prompter":
            continue
        if langs and row.get("lang") not in langs:
            continue
        messages = [{"role": "system", "content": system_prompt}]
        prompt: dict[str, Any] | None = row
        for _ in range(max_turns):
            if prompt is None:
                break
            reply = best_reply(prompt["message_id"])
            if reply is None:
                break
            messages = [*messages, {"role": "user", "content": prompt["text"]}, {"role": "assistant", "content": reply["text"]}]
            examples.append({"messages": messages, "source": f"oasst2:{reply['message_id']}", "kind": "oasst2"})
            prompt = first_followup(reply["message_id"])
    return examples


def load_oasst2(langs: set[str] | None = None, limit: int | None = None) -> list[dict[str, Any]]:
    from datasets import load_dataset

    rows = load_dataset("OpenAssistant/oasst2", split="train")
    examples = build_oasst_threads(rows, langs=langs)
    return examples[:limit] if limit else examples


def load_identity(system_prompt: str = CONFIG.system_prompt) -> list[dict[str, Any]]:
    examples = []
    with (SEED_DIR / "identity.jsonl").open(encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            row = json.loads(line)
            examples.append({
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": row["user"]},
                    {"role": "assistant", "content": row["assistant"]},
                ],
                "source": "identity",
                "kind": "identity",
            })
    return examples
